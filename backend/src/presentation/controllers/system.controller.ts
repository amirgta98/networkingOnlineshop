import { Controller, Get, HttpCode, HttpStatus } from '@nestjs/common';
import { ApiOperation, ApiResponse, ApiTags } from '@nestjs/swagger';
import { buildSmsDiagnostics, type SmsDiagnostics } from '../../infrastructure/sms/sms-delivery-mode.js';

@ApiTags('System')
@Controller('system')
export class SystemController {
  @Get('sms-status')
  @HttpCode(HttpStatus.OK)
  @ApiOperation({
    summary: 'OTP/SMS delivery routing diagnostics (no secrets are exposed)',
  })
  @ApiResponse({
    status: HttpStatus.OK,
    description:
      'Resolved SMS delivery mode (real | telegram | test) together with the environment flags that produced it.',
  })
  getSmsStatus(): SmsDiagnostics {
    return buildSmsDiagnostics();
  }

  @Get('sms-test')
  @HttpCode(HttpStatus.OK)
  @ApiOperation({
    summary: 'Diagnostics for SMS endpoints and DNS resolution',
  })
  async testSmsEndpoints(): Promise<Record<string, unknown>> {
    const results: Record<string, unknown> = {};

    // 1. DNS lookups
    try {
      const dns = await import('node:dns/promises');
      results.dnsConsole = await dns.lookup('console.melipayamak.com');
    } catch (err: unknown) {
      results.dnsConsoleError = err instanceof Error ? err.message : String(err);
    }

    try {
      const dns = await import('node:dns/promises');
      results.dnsRest = await dns.lookup('rest.payamak-panel.com');
    } catch (err: unknown) {
      results.dnsRestError = err instanceof Error ? err.message : String(err);
    }

    // 2. Direct TCP connect test to Melipayamak IP:443
    try {
      const net = await import('node:net');
      results.tcpConsole443 = await new Promise((resolve) => {
        const start = Date.now();
        const socket = net.createConnection({ host: '85.198.11.3', port: 443, timeout: 5000 }, () => {
          const duration = Date.now() - start;
          socket.destroy();
          resolve({ connected: true, durationMs: duration });
        });
        socket.on('error', (e) => resolve({ connected: false, error: e.message }));
        socket.on('timeout', () => {
          socket.destroy();
          resolve({ connected: false, error: 'TCP connect timeout (5000ms)' });
        });
      });
    } catch (e: any) {
      results.tcpConsole443Error = e?.message;
    }

    // 3. Direct TCP connect test to a generic internet host (1.1.1.1:80)
    try {
      const net = await import('node:net');
      results.tcpInternet80 = await new Promise((resolve) => {
        const start = Date.now();
        const socket = net.createConnection({ host: '1.1.1.1', port: 80, timeout: 3000 }, () => {
          const duration = Date.now() - start;
          socket.destroy();
          resolve({ connected: true, durationMs: duration });
        });
        socket.on('error', (e) => resolve({ connected: false, error: e.message }));
        socket.on('timeout', () => {
          socket.destroy();
          resolve({ connected: false, error: 'TCP connect timeout (3000ms)' });
        });
      });
    } catch (e: any) {
      results.tcpInternet80Error = e?.message;
    }

    // 4. HTTP connectivity test to Console
    try {
      const controller = new AbortController();
      const tId = setTimeout(() => controller.abort(), 6000);
      const res = await fetch('https://console.melipayamak.com/api/send', {
        method: 'GET',
        signal: controller.signal,
      });
      clearTimeout(tId);
      results.httpConsole = { status: res.status, ok: res.ok };
    } catch (err: unknown) {
      results.httpConsoleError = err instanceof Error ? err.message : String(err);
      if (err && typeof err === 'object' && 'cause' in err) {
        results.httpConsoleCause = String((err as any).cause);
      }
    }

    // 5. HTTP connectivity test to Rest
    try {
      const controller = new AbortController();
      const tId = setTimeout(() => controller.abort(), 6000);
      const res = await fetch('https://rest.payamak-panel.com', {
        method: 'GET',
        signal: controller.signal,
      });
      clearTimeout(tId);
      results.httpRest = { status: res.status, ok: res.ok };
    } catch (err: unknown) {
      results.httpRestError = err instanceof Error ? err.message : String(err);
      if (err && typeof err === 'object' && 'cause' in err) {
        results.httpRestCause = String((err as any).cause);
      }
    }

    // 6. Read diag.txt generated by deployment script if present
    try {
      const fs = await import('node:fs/promises');
      const path = await import('node:path');
      const diagPath = path.resolve(process.cwd(), 'uploads', 'diag.txt');
      results.vpsDiag = await fs.readFile(diagPath, 'utf8');
    } catch {
      results.vpsDiag = 'diag.txt not found yet';
    }

    return results;
  }
}
